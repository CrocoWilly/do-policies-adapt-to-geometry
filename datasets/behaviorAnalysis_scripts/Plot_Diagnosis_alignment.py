def main():
    parser = argparse.ArgumentParser(
        description="Plot alignment phase behavior analysis metrics from CSV files"
    )
    parser.add_argument(
        "--input", "-i",
        type=str,
        nargs="+",
        required=True,
        help="Paths to input CSV files (generated by Diagnosis2_behaviorAnalysis_alignment.py)"
    )
    parser.add_argument(
        "--title-prefix",
        type=str,
        default=None,
        help="Prefix for plot titles (default: auto-extracted from first input filename)"
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Directory to save output plots (default: current directory)"
    )
    
    args = parser.parse_args()
    
    # Parse all CSV files
    data_list = []
    for csv_path in args.input:
        try:
            data = parse_csv_summary(csv_path)
            data_list.append(data)
            print(f"Parsed: {csv_path}")
            print(f"  Final Yaw Error (median): {data['final_yaw_error_median']:.6f} rad ({np.degrees(data['final_yaw_error_median']):.2f} deg)")
            print(f"  Alignment Steps (median): {data['alignment_steps_median']}")
            print(f"  Alignment Wiggle (median): {data['alignment_wiggle_median']:.6f}")
            print(f"  Yaw Correction (median): {data['yaw_correction_median']:.6f} rad ({np.degrees(data['yaw_correction_median']):.2f} deg)")
        except Exception as e:
            print(f"[ERROR] Failed to parse {csv_path}: {e}")
    
    if not data_list:
        print("No valid CSV files to plot.")
        return
    
    # Auto-extract title_prefix from first input filename if not specified
    # Example: SmallExp3-2_rollout100_clearance112_yaw15_alignment -> SmallExp3-2
    title_prefix = args.title_prefix
    if title_prefix is None:
        first_filename = data_list[0]["filename"]
        # Remove _alignment suffix if present
        first_filename = re.sub(r"_alignment$", "", first_filename)
        parts = first_filename.split("_")
        title_prefix = parts[0] if parts else first_filename
    
    # Determine output paths
    output_dir = Path(args.output_dir) if args.output_dir else Path(".")
    output_dir.mkdir(parents=True, exist_ok=True)
    
    final_yaw_error_path = output_dir / f"{title_prefix}_final_yaw_error.png"
    alignment_steps_path = output_dir / f"{title_prefix}_alignment_steps.png"
    alignment_wiggle_path = output_dir / f"{title_prefix}_alignment_wiggle.png"
    yaw_correction_path = output_dir / f"{title_prefix}_yaw_correction.png"
    
    print("\n" + "=" * 70)
    print("Generating plots...")
    print("=" * 70)
    
    # Plot final yaw error
    plot_final_yaw_error(data_list, title_prefix, str(final_yaw_error_path))
    
    # Plot alignment steps
    plot_alignment_steps(data_list, title_prefix, str(alignment_steps_path))
    
    # Plot alignment wiggle
    plot_alignment_wiggle(data_list, title_prefix, str(alignment_wiggle_path))
    
    # Plot yaw correction
    plot_yaw_correction(data_list, title_prefix, str(yaw_correction_path))


if __name__ == "__main__":
    main()
