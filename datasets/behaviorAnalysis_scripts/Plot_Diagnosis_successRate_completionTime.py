"""
Script to plot success rate and completion time from multiple CSV files.

This script reads CSV files generated by Diagnosis1_successRate_completionTime.py
and creates two bar charts:
    1. Success rate comparison across files
    2. Average completion time comparison across files

Usage:
    python Plot_Diagnosis1_successRate_completionTime.py --input file1.csv file2.csv file3.csv
    python Plot_Diagnosis1_successRate_completionTime.py --input file1.csv file2.csv --title-prefix "SmallExp3-1"
    python Plot_Diagnosis1_successRate_completionTime.py --input file1.csv file2.csv --output-dir ./plots
"""

import argparse
import re
from pathlib import Path
from typing import List, Dict
import matplotlib.pyplot as plt
import numpy as np


def parse_csv_summary(csv_path: str) -> Dict:
    """
    Parse a CSV file and extract summary statistics.
    
    Args:
        csv_path: Path to the CSV file
    
    Returns:
        Dictionary with extracted statistics
    """
    path = Path(csv_path)
    if not path.exists():
        raise FileNotFoundError(f"File not found: {csv_path}")
    
    result = {
        "filename": path.stem,
        "success_rate": 0.0,
        "median_completion_time": 0.0,
        "std_completion_time": 0.0,
    }
    
    with open(path, "r") as f:
        content = f.read()
    
    # Extract success rate
    match = re.search(r"# Success rate:\s*([\d.]+)%", content)
    if match:
        result["success_rate"] = float(match.group(1))
    
    # Extract median completion time and std (new format)
    match = re.search(r"# Median completion time:\s*([\d.]+)\s*steps\s*\(std:\s*([\d.]+)\)", content)
    if match:
        result["median_completion_time"] = float(match.group(1))
        result["std_completion_time"] = float(match.group(2))
    else:
        # Fallback to old format (avg completion time)
        match = re.search(r"# Avg completion time:\s*([\d.]+)\s*steps\s*\(std:\s*([\d.]+)\)", content)
        if match:
            result["median_completion_time"] = float(match.group(1))
            result["std_completion_time"] = float(match.group(2))
    
    return result


def extract_label_from_filename(filename: str) -> str:
    """
    Extract a shorter label from the filename for display.
    
    Args:
        filename: The filename (without extension)
    
    Returns:
        A shorter label string
    """
    # Try to extract clearance and yaw info
    # Example: SmallExp3-1_rollout100_clearance112_yaw-15 -> C112_Y-15
    match = re.search(r"clearance(\d+)_yaw(-?\d+)", filename)
    if match:
        clearance = match.group(1)
        yaw = match.group(2)
        return f"C{clearance}_Y{yaw}"
    
    # Fallback: return last part of filename
    parts = filename.split("_")
    if len(parts) >= 2:
        return "_".join(parts[-2:])
    return filename


def plot_success_rate(
    data_list: List[Dict],
    title_prefix: str = "SmallExp3-1",
    output_path: str = None,
):
    """
    Plot success rate bar chart.
    
    Args:
        data_list: List of dictionaries with parsed CSV data
        title_prefix: Prefix for the plot title
        output_path: Path to save the figure
    """
    labels = [extract_label_from_filename(d["filename"]) for d in data_list]
    success_rates = [d["success_rate"] for d in data_list]
    
    fig, ax = plt.subplots(figsize=(10, 6))
    
    x = np.arange(len(labels))
    bars = ax.bar(x, success_rates, color='steelblue', edgecolor='black')
    
    ax.set_xlabel("Dataset", fontsize=12)
    ax.set_ylabel("Success Rate (%)", fontsize=12)
    ax.set_title(f"{title_prefix} Success Rate (%)", fontsize=14)
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=45, ha='right')
    ax.set_ylim(0, 105)
    
    # Add value labels on bars
    for bar, rate in zip(bars, success_rates):
        height = bar.get_height()
        ax.annotate(f'{rate:.1f}%',
                    xy=(bar.get_x() + bar.get_width() / 2, height),
                    xytext=(0, 3),
                    textcoords="offset points",
                    ha='center', va='bottom', fontsize=10)
    
    plt.tight_layout()
    
    if output_path:
        plt.savefig(output_path, dpi=150)
        print(f"Success rate plot saved to: {output_path}")
    
    plt.show()


def plot_completion_time(
    data_list: List[Dict],
    title_prefix: str = "SmallExp3-1",
    output_path: str = None,
):
    """
    Plot completion time bar chart with error bars.
    
    Args:
        data_list: List of dictionaries with parsed CSV data
        title_prefix: Prefix for the plot title
        output_path: Path to save the figure
    """
    labels = [extract_label_from_filename(d["filename"]) for d in data_list]
    median_times = [d["median_completion_time"] for d in data_list]
    std_times = [d["std_completion_time"] for d in data_list]
    
    fig, ax = plt.subplots(figsize=(10, 6))
    
    x = np.arange(len(labels))
    bars = ax.bar(x, median_times, yerr=std_times, capsize=5,
                  color='coral', edgecolor='black', error_kw={'elinewidth': 2})
    
    ax.set_xlabel("Dataset", fontsize=12)
    ax.set_ylabel("Completion Steps", fontsize=12)
    ax.set_title(f"{title_prefix} Completion Steps (Median, Success Only)", fontsize=14)
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=45, ha='right')
    
    # Add value labels on bars
    for bar, median, std in zip(bars, median_times, std_times):
        height = bar.get_height()
        ax.annotate(f'{median:.1f}',
                    xy=(bar.get_x() + bar.get_width() / 2, height + std + 1),
                    xytext=(0, 3),
                    textcoords="offset points",
                    ha='center', va='bottom', fontsize=10)
    
    plt.tight_layout()
    
    if output_path:
        plt.savefig(output_path, dpi=150)
        print(f"Completion time plot saved to: {output_path}")
    
    plt.show()


def main():
    parser = argparse.ArgumentParser(
        description="Plot success rate and completion time from CSV files"
    )
    parser.add_argument(
        "--input", "-i",
        type=str,
        nargs="+",
        required=True,
        help="Paths to input CSV files"
    )
    parser.add_argument(
        "--title-prefix",
        type=str,
        default=None,
        help="Prefix for plot titles (default: auto-extracted from first input filename)"
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Directory to save output plots (default: current directory)"
    )
    
    args = parser.parse_args()
    
    # Parse all CSV files
    data_list = []
    for csv_path in args.input:
        try:
            data = parse_csv_summary(csv_path)
            data_list.append(data)
            print(f"Parsed: {csv_path}")
            print(f"  Success Rate: {data['success_rate']:.2f}%")
            print(f"  Median Completion Time: {data['median_completion_time']:.2f} (std: {data['std_completion_time']:.2f})")
        except Exception as e:
            print(f"[ERROR] Failed to parse {csv_path}: {e}")
    
    if not data_list:
        print("No valid CSV files to plot.")
        return
    
    # Auto-extract title_prefix from first input filename if not specified
    # Example: SmallExp3-2_rollout100_clearance112_yaw15 -> SmallExp3-2
    title_prefix = args.title_prefix
    if title_prefix is None:
        first_filename = data_list[0]["filename"]
        parts = first_filename.split("_")
        title_prefix = parts[0] if parts else first_filename
    
    # Determine output paths
    output_dir = Path(args.output_dir) if args.output_dir else Path(".")
    output_dir.mkdir(parents=True, exist_ok=True)
    
    success_rate_path = output_dir / f"{title_prefix}_success_rate.png"
    completion_time_path = output_dir / f"{title_prefix}_completion_steps.png"
    
    print("\n" + "=" * 70)
    print("Generating plots...")
    print("=" * 70)
    
    # Plot success rate
    plot_success_rate(data_list, title_prefix, str(success_rate_path))
    
    # Plot completion time
    plot_completion_time(data_list, title_prefix, str(completion_time_path))


if __name__ == "__main__":
    main()
