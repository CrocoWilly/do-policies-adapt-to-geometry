def main():
    parser = argparse.ArgumentParser(
        description="Plot insertion phase behavior analysis metrics from CSV files"
    )
    parser.add_argument(
        "--input", "-i",
        type=str,
        nargs="+",
        required=True,
        help="Paths to input CSV files (generated by Diagnosis2_behaviorAnalysis_insertion.py)"
    )
    parser.add_argument(
        "--title-prefix",
        type=str,
        default=None,
        help="Prefix for plot titles (default: auto-extracted from first input filename)"
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Directory to save output plots (default: current directory)"
    )
    
    args = parser.parse_args()
    
    # Parse all CSV files
    data_list = []
    for csv_path in args.input:
        try:
            data = parse_csv_summary(csv_path)
            data_list.append(data)
            print(f"Parsed: {csv_path}")
            print(f"  Success Rate: {data['success_count']}/{data['total_count']} ({100*data['success_count']/max(1,data['total_count']):.1f}%)")
            print(f"  Contact Wiggle (median): {data['contact_wiggle_median'] * 100:.4f} cm")
            print(f"  Contact Push Speed (median): {data['contact_push_speed_median'] * 100:.4f} cm/step")
            print(f"  Contact Pause Count (median): {int(data['contact_pause_count_median'])}")
        except Exception as e:
            print(f"[ERROR] Failed to parse {csv_path}: {e}")
    
    if not data_list:
        print("No valid CSV files to plot.")
        return
    
    # Auto-extract title_prefix from first input filename if not specified
    # Example: SmallExp3-2_rollout100_clearance112_yaw15_insertion -> SmallExp3-2
    title_prefix = args.title_prefix
    if title_prefix is None:
        first_filename = data_list[0]["filename"]
        # Remove _insertion suffix if present
        first_filename = re.sub(r"_insertion$", "", first_filename)
        parts = first_filename.split("_")
        title_prefix = parts[0] if parts else first_filename
    
    # Determine output paths
    output_dir = Path(args.output_dir) if args.output_dir else Path(".")
    output_dir.mkdir(parents=True, exist_ok=True)
    
    contact_wiggle_path = output_dir / f"{title_prefix}_contact_wiggle_success.png"
    contact_wiggle_per_step_path = output_dir / f"{title_prefix}_contact_wiggle_per_step_success.png"
    contact_steps_path = output_dir / f"{title_prefix}_contact_steps_success.png"
    contact_push_speed_path = output_dir / f"{title_prefix}_contact_push_speed_success.png"
    mean_dz_per_step_path = output_dir / f"{title_prefix}_mean_dz_per_step_success.png"
    contact_pause_count_path = output_dir / f"{title_prefix}_contact_pause_count_success.png"
    
    print("\n" + "=" * 70)
    print("Generating plots...")
    print("=" * 70)
    
    # Plot contact wiggle
    plot_contact_wiggle(data_list, title_prefix, str(contact_wiggle_path))
    
    # Plot contact wiggle per step
    plot_contact_wiggle_per_step(data_list, title_prefix, str(contact_wiggle_per_step_path))
    
    # Plot contact steps
    plot_contact_steps(data_list, title_prefix, str(contact_steps_path))
    
    # Plot contact push speed
    plot_contact_push_speed(data_list, title_prefix, str(contact_push_speed_path))
    
    # Plot mean dz per step
    plot_mean_dz_per_step(data_list, title_prefix, str(mean_dz_per_step_path))
    
    # Plot contact pause count
    plot_contact_pause_count(data_list, title_prefix, str(contact_pause_count_path))


if __name__ == "__main__":
    main()
